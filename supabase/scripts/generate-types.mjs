import { writeFile, readFile } from 'node:fs/promises';
import { createTestDatabase } from '../tests/test-db.mjs';

const database = await createTestDatabase();
try {
  const { rows: columns } = await database.query(`select table_name,column_name,data_type,is_nullable
    from information_schema.columns where table_schema='public' order by table_name,ordinal_position`);
  const tables = new Map();
  for (const column of columns) {
    const type = { uuid: 'string', text: 'string', bigint: 'number', integer: 'number', jsonb: 'Json', 'timestamp with time zone': 'string' }[column.data_type];
    if (!type) throw new Error(`Unsupported type ${column.data_type}`);
    const fields = tables.get(column.table_name) ?? [];
    fields.push(`        ${column.column_name}: ${type}${column.is_nullable === 'YES' ? ' | null' : ''};`);
    tables.set(column.table_name, fields);
  }
  const { rows: functions } = await database.query(`select routine_name from information_schema.routines
    where routine_schema='public' order by routine_name`);
  const output = `// Generated by supabase/scripts/generate-types.mjs from the tested PostgreSQL schema.\n` +
    `// Client tables are read-only; writes go through validated RPCs.\n` +
    `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n` +
    `export type Database = { public: {\n  Tables: {\n` +
    [...tables].map(([name, fields]) => `    ${name}: {\n      Row: {\n${fields.join('\n')}\n      };\n      Insert: never; Update: never; Relationships: [];\n    };`).join('\n') +
    `\n  };\n  Views: { [_ in never]: never };\n  Functions: {\n` +
    functions.map(({ routine_name }) => `    ${routine_name}: { Args: { request: Json }; Returns: Json };`).join('\n') +
    `\n  };\n  Enums: { [_ in never]: never };\n  CompositeTypes: { [_ in never]: never };\n} };\n`;
  const path = new URL('../../android-app/src/cloud/database.types.ts', import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== output) throw new Error('Database types differ from the tested schema. Run npm run types in supabase.');
  } else await writeFile(path, output);
  console.log(`Verified ${tables.size} tables and ${functions.length} RPC types from PostgreSQL.`);
} finally { await database.close(); }
